#!/usr/bin/env python3
"""Build src/geo.js from Natural Earth / US Census TopoJSON (npm: world-atlas, us-atlas).

    npm pack world-atlas us-atlas && tar xzf ... ; python3 tools/geo.py <world-dir> <us-dir>

Writes compact lon/lat rings: GEO.land (world, 1:110m), GEO.usa (lower 48 outline) and
GEO.states (interior state borders, lower 48).
"""
import json, sys, os

def decode(topo):
    sx, sy = topo['transform']['scale']; tx, ty = topo['transform']['translate']
    arcs = []
    for a in topo['arcs']:
        x = y = 0; pts = []
        for dx, dy in a:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs

def ring(arcs, idx):
    out = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(a if not out else a[1:])
    return out

def polys(arcs, geom):
    if geom['type'] == 'Polygon': return [[ring(arcs, r) for r in geom['arcs']]]
    if geom['type'] == 'MultiPolygon': return [[ring(arcs, r) for r in p] for p in geom['arcs']]
    if geom['type'] == 'GeometryCollection':
        return [p for g in geom['geometries'] for p in polys(arcs, g)]
    return []

def simplify(pts, tol):
    """Douglas-Peucker."""
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    if pts[0] == pts[-1]:  # closed ring: split at the point farthest from the start
        far = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
        keep[far] = True; stack = [(0, far), (far, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; L = (dx * dx + dy * dy) ** .5 or 1e-9
        best, bi = 0, -1
        for i in range(a + 1, b):
            d = abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / L
            if d > best: best, bi = d, i
        if best > tol:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def fmt(r, nd=2): return [[round(x, nd), round(y, nd)] for x, y in r]

world_dir, us_dir = sys.argv[1], sys.argv[2]
w = json.load(open(os.path.join(world_dir, 'land-110m.json')))
land = [fmt(p[0], 1) for p in polys(decode(w), w['objects']['land']) if len(p[0]) > 3]

n = json.load(open(os.path.join(us_dir, 'nation-10m.json')))
arcs = decode(n)
usa = []
for p in polys(arcs, n['objects']['nation']):
    r = p[0]
    xs = [q[0] for q in r]; ys = [q[1] for q in r]
    if min(xs) > -125.5 and max(xs) < -66 and min(ys) > 24 and max(ys) < 50 and len(r) > 30:
        s = simplify(r, 0.02)
        if len(s) > 8: usa.append(fmt(s))

s = json.load(open(os.path.join(us_dir, 'states-10m.json')))
arcs = decode(s)
geoms = s['objects']['states']['geometries']
use = {}
for g in geoms:
    if g['id'] in ('02', '15', '72', '78', '60', '66', '69'): continue
    def walk(a):
        for x in a:
            if isinstance(x, list): walk(x)
            else: use[x if x >= 0 else ~x] = use.get(x if x >= 0 else ~x, 0) + 1
    walk(g['arcs'])
states = [fmt(simplify(arcs[i], 0.03)) for i, c in use.items() if c >= 2 and len(arcs[i]) > 1]

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'geo.js')
with open(out, 'w') as f:
    f.write('/* Generated by tools/geo.py from world-atlas (Natural Earth, public domain) and us-atlas (US Census, public domain). */\n')
    f.write('window.GEO = ' + json.dumps({'land': land, 'usa': usa, 'states': states}, separators=(',', ':')) + ';\n')
print('land rings', len(land), 'pts', sum(map(len, land)), '| usa rings', len(usa), 'pts', sum(map(len, usa)), '| state arcs', len(states), 'pts', sum(map(len, states)), '| bytes', os.path.getsize(out))
